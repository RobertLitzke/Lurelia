"""Write palette.js for the structure viewer: material name -> base colour.

Run from anywhere after adding or recolouring materials:
    python tools/structure_viewer/build_palette.py
"""
import glob
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.normpath(os.path.join(here, "..", ".."))
# The engine's built-in materials (src/world/matlib.rs BUILTIN) have no library
# file; these are their main colours from src/render/textures.rs.
palette = {
    "grass": [96, 140, 60], "dirt": [120, 88, 60], "sand": [214, 182, 124],
    "stone": [150, 128, 112], "stone_dark": [78, 84, 104], "stone_light": [206, 172, 128],
    "bark": [104, 64, 40], "leaves": [48, 92, 48], "pine": [26, 76, 58],
    "planks": [178, 132, 88], "gravel": [144, 136, 128], "birch_bark": [228, 222, 208],
    "leaves_autumn": [214, 98, 30], "snow": [238, 242, 248],
    "birch_leaves": [124, 150, 60], "brick": [166, 92, 70],
}
mats = {}
for path in sorted(glob.glob(os.path.join(root, "library", "materials", "*.json"))):
    with open(path, encoding="utf-8") as f:
        m = json.load(f)
    mats[m.get("name") or os.path.splitext(os.path.basename(path))[0]] = m


def base_of(name, depth=0):
    """A material's base colour, through `like` as src/inherit.rs resolves it:
    its own base if it gives one, else its parent's repainted by its `shade`
    and `hue`."""
    m = mats.get(name)
    if m is None or depth > 8:
        return None
    own = (m.get("texture") or {}).get("base")
    if own:
        return own[:3]
    parent = base_of(m.get("like"), depth + 1) if m.get("like") else None
    if parent is None:
        return None
    s, h = m.get("shade", 1.0), m.get("hue", 0.0)
    mul = [s * (1 + h), s, s * (1 - h)]
    return [max(0, min(255, round(c * k))) for c, k in zip(parent, mul)]


for name in mats:
    base = base_of(name)
    if base:
        palette[name] = base

with open(os.path.join(here, "palette.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by build_palette.py from library/materials. Do not edit.\n")
    f.write("window.PALETTE = ")
    json.dump(palette, f, separators=(",", ":"))
    f.write(";\n")
print(f"{len(palette)} materials")
