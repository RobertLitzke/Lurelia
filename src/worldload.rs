//! Loading a chronicle world for the game: the library, its materials, the built
//! world, and the library creatures as models and species.

use crate::entities::Species;
use crate::library::{self, Library};
use crate::models::{self, Model};
use crate::world::chronicle;
use crate::world::fields::World;
use crate::world::shape;
use std::collections::HashMap;
use std::sync::{Arc, Mutex};

/// The world to play, set from `--world` before the game starts and by the world
/// selector (L). "random" plays the noise-generated random island; a world that
/// fails to load is an error (shown under the title menu), never a fallback.
static WORLD: Mutex<Option<String>> = Mutex::new(None);

pub const DEFAULT_WORLD: &str = "glassfall";

/// A collectible's model and how the game shows it.
#[derive(Clone)]
pub struct ItemModel {
    pub name: String,
    pub display: String,
    pub model: usize,
    pub spin: bool,
}

pub struct Loaded {
    pub world: Arc<World>,
    pub items: Vec<ItemModel>,
    /// Creature models, in library order; species model indices count from 0
    /// here and are offset by the caller.
    pub models: Vec<Model>,
    pub species: Vec<Species>,
    /// The library models' palette blocks, one after another. They go in the
    /// palette straight after the fixed block (models::FIXED_SLOTS), which is
    /// where each model's `block` points.
    pub colours: Vec<[f32; 4]>,
    /// The world's platforms (src/platforms.rs), compiled, and where their
    /// models start in `models`.
    pub platforms: Vec<crate::platforms::Built>,
    pub platform_models: usize,
    /// The world's platforms and its generated doors, in one list: what
    /// `platforms` and the models were built from, so whoever steps them
    /// has the same list.
    pub platform_defs: Vec<crate::platforms::PlatformDef>,
}

pub fn selected() -> String {
    WORLD.lock().unwrap().clone().unwrap_or_else(|| DEFAULT_WORLD.to_string())
}

pub fn select(name: &str) {
    *WORLD.lock().unwrap() = Some(name.to_string());
}

/// Where world folders live, in lookup order: `worlds/` is published with the
/// game, `local/worlds/` holds worlds kept out of the repository (git ignores
/// `local/`). A name in both resolves to `worlds/`.
pub const WORLD_DIRS: [&str; 2] = ["worlds", "local/worlds"];

/// The folder of a world by name: the first of `WORLD_DIRS` that has it, or
/// `worlds/<name>` when none does (so errors name the usual place).
pub fn world_dir(name: &str) -> std::path::PathBuf {
    let root = library::data_root();
    WORLD_DIRS
        .iter()
        .map(|d| root.join(d).join(name))
        .find(|p| p.join("chronicle.json").exists())
        .unwrap_or_else(|| root.join("worlds").join(name))
}

/// Every world folder with a chronicle, by kind and then by name (places to
/// explore, arenas, the workshop), then the random island when a
/// `local/worlds/random/` folder asks for it (it is generated by code, so the
/// folder holds nothing the game reads). A world whose world.json says
/// `"listed": false` is kept for tests and headless measuring (`--world`
/// still opens it) but left off the menus' list.
pub fn available() -> Vec<String> {
    let root = library::data_root();
    let mut out: Vec<String> = WORLD_DIRS
        .iter()
        .filter_map(|d| std::fs::read_dir(root.join(d)).ok())
        .flat_map(|rd| {
            rd.filter_map(|e| e.ok())
                .filter(|e| e.path().join("chronicle.json").exists())
                .filter_map(|e| e.file_name().into_string().ok())
        })
        .filter(|w: &String| crate::launch::info(w).listed)
        .collect();
    // Places to explore first, then the arenas, then the workshop's tests
    // and imports; by name within each.
    out.sort_by_key(|w| (crate::launch::info(w).kind(), w.clone()));
    out.dedup();
    if root.join("local/worlds/random").is_dir() {
        out.push("random".to_string());
    }
    out
}

/// Load the library alone, with every material counted as reached, and
/// install its materials unless a world's are installed already (the
/// renderer needs a table before any world loads; a world's own one wins).
pub fn library() -> (Library, Vec<String>) {
    let (lib, errors) = Library::load(&library::data_root());
    if !crate::world::matlib::installed() {
        crate::world::matlib::install(&lib);
    }
    (lib, errors)
}

/// Load the library with material ids for world `name` (`reach`) and install
/// them. Reached materials that found no id are reported as errors.
pub fn library_for(name: &str) -> (Library, Vec<String>) {
    let root = library::data_root();
    let (mut lib, mut errors) = Library::load(&root);
    let dir = world_dir(name);
    // The noise island has no chronicle, and draws nothing out of the
    // library: its ground is the built-in stone, dirt, sand and snow and its
    // trees the built-in bark and leaves. It used to reach every material
    // for want of a world file to read, which left no id free for the grain
    // copies of the last wood and built a texture layer for all 273. It now
    // reaches what the engine names in code, as any world does, and nothing
    // else (`reach` starts from ENGINE_MATERIALS, and finds no world.json or
    // chronicle.json to add to it).
    let mut r = reach(&root.join("library"), &dir, &lib);
    lib.reach_coats(&mut r);
    for m in lib.assign_ids(Some(r)) {
        errors.push(format!("material {m}: no voxel id left in world {name} (it reaches more than 238 materials with their grain copies)"));
    }
    errors.extend(round_edges_for_world(&dir, &mut lib));
    crate::world::matlib::install(&lib);
    (lib, errors)
}

/// Bevel the materials a world's `round_edges` list names (see
/// `WorldDef::round_edges`), for this world's table only. Ground slopes are
/// turned off for them: a rounded corner with sloped ground near it stays
/// square. Returns an error for each name the library doesn't have.
fn round_edges_for_world(dir: &std::path::Path, lib: &mut Library) -> Vec<String> {
    let Some(names) = std::fs::read_to_string(dir.join("world.json"))
        .ok()
        .and_then(|t| serde_json::from_str::<serde_json::Value>(&t).ok())
        .and_then(|v| v.get("round_edges").cloned())
    else {
        return Vec::new();
    };
    let names: Vec<String> = serde_json::from_value(names).unwrap_or_default();
    let mut errors = Vec::new();
    for n in names {
        match lib.materials.iter_mut().find(|m| m.name == n) {
            Some(m) => {
                m.bevel_steps = true;
                m.smooth = false;
            }
            None => errors.push(format!("world.json round_edges: no material {n}")),
        }
    }
    errors
}

