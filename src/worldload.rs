/// Every library name world `dir` can reach: any string in its world.json
/// and chronicle.json that names a library entry, then any string in those
/// entries' files, and so on (a biome's plants, a plant's bark, a structure's
/// slots, a sign style's post, a parent named by `like`), and any string in a
/// .json data file the world names (a city import). The biomes are the world's `biomes` list
/// (all of them when it has none). Over-counting is harmless: it only costs
/// ids; a name missed still gets an id when there is room.
pub fn reach(lib_dir: &std::path::Path, dir: &std::path::Path, lib: &Library) -> std::collections::HashSet<String> {
    use serde_json::Value;
    fn strings(v: &Value, out: &mut Vec<String>) {
        match v {
            Value::String(s) => out.push(s.clone()),
            Value::Array(a) => a.iter().for_each(|x| strings(x, out)),
            Value::Object(o) => o.values().for_each(|x| strings(x, out)),
            _ => {}
        }
    }
    let read = |p: std::path::PathBuf| std::fs::read_to_string(p).ok().and_then(|t| serde_json::from_str::<Value>(&t).ok());
    let mut todo: Vec<String> = ENGINE_MATERIALS.iter().map(|s| s.to_string()).collect();
    let world = read(dir.join("world.json")).unwrap_or(Value::Null);
    strings(&world, &mut todo);
    // The platforms the shooter stamps under its pads are named by no file:
    // they follow from each pad's kind and gun (`PickupDef::pad_material`).
    if let Some(Value::Array(pads)) = world.get("shooter").and_then(|s| s.get("pickups")) {
        for p in pads {
            if let Ok(p) = serde_json::from_value::<crate::world::fields::PickupDef>(p.clone()) {
                todo.extend(p.pad_material());
            }
        }
    }
    if let Some(c) = read(dir.join("chronicle.json")) {
        strings(&c, &mut todo);
    }
    // A world that lists no biomes may use any of them. The noise island
    // has no world.json at all and uses none: its ground is the built-in
    // stone, dirt, sand and snow, and its trees the built-in bark and
    // leaves, so reaching every biome there only ate the ids the grain
    // copies want.
    if !world.is_null() && world.get("biomes").is_none() {
        todo.extend(lib.biomes.iter().map(|b| b.name.clone()));
    }
    // A world may hand an event a data file of its own (a city import's
    // `city.json`), and the materials its buildings, streets and trees name
    // appear nowhere else. Read any .json the world or chronicle names,
    // relative to the world folder, so those names reach too.
    for f in todo.clone() {
        if f.ends_with(".json") {
            if let Some(v) = read(dir.join(&f)) {
                strings(&v, &mut todo);
            }
        }
    }
    // The kinds whose files can name materials or other entries.
    let kinds = ["biomes", "plants", "structures", "signs", "kits", "cities"];
    let mut seen = std::collections::HashSet::new();
    while let Some(n) = todo.pop() {
        if !seen.insert(n.clone()) {
            continue;
        }
        for k in kinds {
            let p = lib_dir.join(k).join(format!("{n}.json"));
            if let Some(v) = read(p) {
                strings(&v, &mut todo);
            }
        }
    }
    seen
}

/// Build a world by name. Errors when the folder is missing or broken.
pub fn load(name: &str) -> Result<Loaded, String> {
    if name == "random" {
        return Err("random island selected".into());
    }
    let dir = world_dir(name);
    if !dir.join("chronicle.json").exists() {
        return Err(format!("no world at {}", dir.display()));
    }
    let (lib, errors) = library_for(name);
    for e in &errors {
        eprintln!("library: {e}");
    }
    let world = chronicle::build_world(&dir, lib)?;
    for w in &world.warnings {
        eprintln!("world {name}: {w}");
    }
    let (mut models, species, items, mut colours, mut problems) = creatures(&world);
    // The platforms' models go after the creatures', with their palette
    // blocks after the creatures' blocks.
    let platform_models = models.len();
    // The world's own platforms, and then a plate for every door the
    // chronicle put on the land (`platforms::doors_in`): until now a door
    // was terrain, so it could not open and digging eroded it.
    let mut platform_defs = world.def.platforms.clone();
    let doors = crate::platforms::doors_in(&world);
    if !doors.is_empty() {
        eprintln!("world {name}: {} doors", doors.len());
    }
    platform_defs.extend(doors);
    let (platforms, plats) = crate::platforms::build(&platform_defs, &world.lib, &mut colours, &mut problems);
    models.extend(plats);
    for e in &problems {
        eprintln!("world {name}: {e}");
    }
    Ok(Loaded {
        world: Arc::new(world),
        models,
        species,
        items,
        colours,
        platforms,
        platform_models,
        platform_defs,
    })
}

/// The creatures and collectibles a built world can show: those its biomes
/// list (only biomes some cell took) and the items its events buried.
pub fn used_entries(world: &World) -> std::collections::HashSet<String> {
    let lib = &world.lib;
    let mut present = vec![false; lib.biomes.len()];
    for &b in &world.f.biome {
        present[b as usize] = true;
    }
    let mut used = std::collections::HashSet::new();
    for (b, def) in lib.biomes.iter().enumerate() {
        if present[b] {
            used.extend(def.creatures.iter().map(|c| c.creature.clone()));
            used.extend(def.collectibles.iter().map(|c| c.item.clone()));
        }
    }
    // The VG_SPAWN dev hook (creatures/spawn.rs) may name a creature no biome
    // here lists, to look at it before any world has it.
    if let Ok(v) = std::env::var("VG_SPAWN") {
        used.extend(v.split(',').map(|s| s.trim().to_string()).filter(|s| !s.is_empty()));
    }
    // Hunters and their prey come along with whoever is listed, and rare
    // morphs with their parents (a morph of a morph too).
    for _ in 0..4 {
        for c in &lib.creatures {
            if used.contains(&c.name) {
                used.extend(c.behaviour.hunts.iter().filter(|n| *n != "player").cloned());
            }
            if c.rarity > 0.0 && c.like.as_ref().is_some_and(|p| used.contains(p)) {
                used.insert(c.name.clone());
            }
        }
    }
    used.extend(world.items.iter().map(|i| i.kind.clone()));
    used
}

/// Compile library creatures into models and resolve who flees and hunts
/// whom. Only the entries this world uses (`used_entries`) are built; the
/// others compile to empty models that are never spawned. Each built model
/// gets its own block of palette colours (models::FIXED_SLOTS), so a world
/// can use any number of colours and each model up to models::PALETTE_SLOTS.
/// Models, species and item models for the creatures and collectibles a world
/// uses, the palette colours they need, and any problems found.
pub fn creatures(world: &World) -> (Vec<Model>, Vec<Species>, Vec<ItemModel>, Vec<[f32; 4]>, Vec<String>) {
    let lib = &world.lib;
    let used = used_entries(world);
    let mut problems = Vec::new();
    let mut colours: Vec<[f32; 4]> = Vec::new();
    let mut models_out = Vec::new();
    let mut parts_out: Vec<Model> = Vec::new();
    // Which creatures ended up with a skeleton worth drawing.
    let mut has_bones: std::collections::HashSet<String> = Default::default();
    // Creatures first, then collectibles, one model each.
    struct Src<'a> {
        name: &'a str,
        colors: &'a HashMap<String, Vec<f32>>,
        ops: &'a [crate::library::Op],
        voxel: f32,
        half_w: f32,
        height: f32,
        rig: Option<&'a crate::anim::RigDef>,
        /// Leaves a skeleton, so one is derived for it (creatures::age).
        bones: bool,
        /// Its entry asked for bones outright, rather than getting them from
        /// its size: worth a complaint if they don't read.
        bones_asked: bool,
    }
    let srcs: Vec<Src> = lib
        .creatures
        .iter()
        .map(|c| Src {
            name: &c.name,
            colors: &c.colors,
            ops: &c.ops,
            voxel: c.voxel,
            half_w: c.half_w,
            height: c.height,
            rig: c.rig.as_ref(),
            bones: crate::creatures::age::Stages::resolve(&c.ages, c.height).bones,
            bones_asked: c.ages.bones.as_deref() == Some("full"),
        })
        .chain(lib.collectibles.iter().map(|c| Src {
            name: &c.name,
            colors: &c.colors,
            ops: &c.ops,
            voxel: c.voxel,
            half_w: 0.15,
            height: 0.2,
            rig: None,
            bones: false,
            bones_asked: false,
        }))
        .collect();
    for c in &srcs {
        let mut slot: HashMap<String, u8> = HashMap::new();
        if !used.contains(c.name) {
            models_out.push(models::from_cells(&[0u8; 32 * 32 * 32], c.voxel, c.half_w, c.height));
            continue;
        }
        // This model's block of the palette: its colours, then the two bone
        // colours if it may leave a skeleton (anim/bones.rs). Its part and
        // skeleton models use the same block.
        let start = colours.len();
        let block = (models::FIXED_SLOTS + start) as u32;
        let mut names: Vec<&String> = c.colors.keys().collect();
        names.sort();
        for name in names {
            let s = models::block_slot(&mut colours, start, models::linear_colour(&c.colors[name]));
            slot.insert(name.clone(), s);
        }
        let named = colours.len();
        let (bone_slot, bone_dark_slot) = if c.bones {
            (
                models::block_slot(&mut colours, start, models::linear_colour(&[238.0, 232.0, 214.0])),
                models::block_slot(&mut colours, start, models::linear_colour(&[186.0, 176.0, 152.0])),
            )
        } else {
            (0, 0)
        };
        problems.extend(models::block_problem(c.name, colours.len() - start));
        let resolve = |n: &str| -> Option<u8> {
            if n == "air" {
                return Some(0);
            }
            slot.get(n).copied()
        };
        let s = shape::compile(c.ops, [32, 32, 32], &resolve);
        let mut model = models::from_cells(&s.mat, c.voxel, c.half_w, c.height);
        model.block = block;
        if let Some(def) = c.rig {
            // Part models go after every whole model (see below).
            let sliced = crate::anim::slice::slice(def, c.ops, &s.mat, &|n| resolve(n).is_some(), c.voxel, c.half_w, c.height);
            let base = sliced.rig.clone();
            // Anything big enough to leave bones gets the skeleton inside it
            // derived from the same voxels (anim/bones.rs).
            // A skeleton nobody could read is no skeleton: a thin creature
            // can be tall and still come out with a dozen voxels of bone.
            let skeleton = c
                .bones
                .then(|| crate::anim::bones::skeletonise(&sliced, bone_slot, bone_dark_slot, c.voxel, c.half_w, c.height))
                .and_then(|(cells, parts)| {
                    let n = crate::anim::bones::voxels(&cells);
                    if n >= crate::anim::bones::MIN_BONE_VOXELS {
                        Some(parts)
                    } else {
                        if c.bones_asked {
                            problems.push(format!("{}: asked for bones but only {n} voxels of them read; set \"ages\": {{\"bones\": \"none\"}}", c.name));
                        }
                        None
                    }
                });
            let mut rig = base.clone();
            rig.offset_models(srcs.len() + parts_out.len());
            parts_out.extend(sliced.parts.into_iter().map(|mut m| {
                m.block = block;
                m
            }));
            model.rig = Some(rig);
            if let Some(parts) = skeleton {
                let mut srig = base;
                srig.offset_models(srcs.len() + parts_out.len());
                parts_out.extend(parts.into_iter().map(|mut m| {
                    m.block = block;
                    m
                }));
                model.skeleton = Some(srig);
            }
        }
        if model.skeleton.is_some() {
            has_bones.insert(c.name.to_string());
        } else {
            // No skeleton came of it, so the bone colours are not wanted.
            colours.truncate(named);
        }
        models_out.push(model);
    }
    models_out.extend(parts_out);
    let mut species: Vec<Species> = lib
        .creatures
        .iter()
        .enumerate()
        .map(|(k, c)| Species {
            name: c.name.clone(),
            model: k,
            beh: c.behaviour.clone(),
            flees: c.behaviour.flees_from.iter().filter_map(|n| lib.creature(n)).collect(),
            hunts: c.behaviour.hunts.iter().filter_map(|n| lib.creature(n)).collect(),
            flees_player: c.behaviour.flees_from.iter().any(|n| n == "player"),
            like: c.like.clone(),
            quota: k,
            water: None,
            is_water_form: false,
            vary: c.vary.clone(),
            coats: crate::variety::wears(&lib.creature_coats(k), &c.colors),
            morphs: lib.creature_morphs(k),
            ages: {
                let mut a = crate::creatures::age::Stages::resolve(&c.ages, c.height);
                a.bones &= has_bones.contains(&c.name);
                a
            },
            aged_tint: crate::variety::aged_tint(&c.colors.values().map(|v| [0, 1, 2].map(|i| models::linear_colour(v)[i])).collect::<Vec<_>>()),
        })
        .collect();
    water_forms(&mut species, lib);
    let n = lib.creatures.len();
    let items = lib
        .collectibles
        .iter()
        .enumerate()
        .map(|(k, c)| ItemModel {
            name: c.name.clone(),
            display: c.display.clone(),
            model: n + k,
            spin: c.spin,
        })
        .collect();
    (models_out, species, items, colours, problems)
}

/// Build the second form of every species whose entry has an `in_water`
/// block, and link the two. The water form shares the land form's model,
/// colours, variation and ages, and fills its quota, so one library entry and
/// one name covers an animal on the bank and in the water: a biome lists
/// `alligator`, and where it lands decides which form it is.
///
/// A rare morph inherits `in_water` with the rest of its parent, so it gets a
/// water form too; the water form's morph list points at those, so Old Pale
/// can be met swimming or hauled out.
fn water_forms(species: &mut Vec<Species>, lib: &crate::library::Library) {
    let mut made: Vec<(usize, usize)> = Vec::new();
    for k in 0..species.len() {
        let Some(beh) = lib.creatures[k].in_water.clone() else {
            continue;
        };
        let land = &species[k];
        let twin = Species {
            name: format!("{}@water", land.name),
            model: land.model,
            flees: beh.flees_from.iter().filter_map(|n| lib.creature(n)).collect(),
            hunts: beh.hunts.iter().filter_map(|n| lib.creature(n)).collect(),
            flees_player: beh.flees_from.iter().any(|n| n == "player"),
            beh,
            like: land.like.clone(),
            quota: land.quota,
            water: Some(k),
            is_water_form: true,
            vary: land.vary.clone(),
            // The same animal, so the same coats: an albino alligator is
            // albino among the knees as well as on the bank.
            coats: land.coats.clone(),
            morphs: Vec::new(),
            ages: land.ages,
            aged_tint: land.aged_tint,
        };
        made.push((k, species.len()));
        species.push(twin);
    }
    for &(land, twin) in &made {
        species[land].water = Some(twin);
    }
    // A water form's morphs are its land form's morphs' own water forms; a
    // morph without one cannot swim, so it is left out rather than dropped
    // into the water moving like a land animal.
    for &(land, twin) in &made {
        let morphs: Vec<(usize, f32)> = species[land].morphs.clone().into_iter().filter_map(|(m, chance)| species[m].water.map(|mw| (mw, chance))).collect();
        species[twin].morphs = morphs;
    }
}
